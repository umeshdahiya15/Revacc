class _Decoder:
    """Local decoder stand-in; no provider response fields leave transport scope."""

    def automodel_receipt(self, _payload: object) -> OfficialAutomodelReceipt:
        return OfficialAutomodelReceipt()

    def project(self, _payload: object) -> OfficialSwissModelProject:
        return OfficialSwissModelProject(state="queued")

    def project_model_summary(self, _payload: object) -> OfficialSwissModelModelSummary:
        return OfficialSwissModelModelSummary()


def _routes(
    *,
    model_pdb_url=None,
) -> OfficialSwissModelCoreApiRoutes:
    return OfficialSwissModelCoreApiRoutes(
        automodel_url="https://swissmodel.expasy.org/automodel/",
        project_url=lambda project_id: f"https://swissmodel.expasy.org/project/{project_id}/",
        project_models_summary_url=(
            lambda project_id: f"https://swissmodel.expasy.org/project/{project_id}/models/"
        ),
        model_pdb_url=(
            model_pdb_url
            or (
                lambda project_id, model_id:
                f"https://swissmodel.expasy.org/project/{project_id}/model/{model_id}/pdb/"
            )
        ),
    )


def _core_transport(
    monkeypatch: pytest.MonkeyPatch,
    handler,
    *,
    routes: OfficialSwissModelCoreApiRoutes | None = None,
) -> OfficialSwissModelCoreApiHttpTransport:
    # This generated value stays only in the process environment and request
    # construction; no fixture or assertion serializes it.
    monkeypatch.setenv("SWISSMODEL_API_TOKEN", secrets.token_urlsafe(32))
    return OfficialSwissModelCoreApiHttpTransport(
        routes=routes or _routes(),
        decoder=_Decoder(),
        policy=SwissModelRetryPolicy(
            connect_timeout_seconds=1.0,
            read_timeout_seconds=1.0,
            overall_timeout_seconds=2.0,
        ),
        http_transport=httpx.MockTransport(handler),
    )


def _pdb_response(pdb_text: str) -> httpx.Response:
    return httpx.Response(
        200,
        headers={"Content-Type": "chemical/x-pdb"},
        content=pdb_text.encode("utf-8"),
    )


@pytest.mark.asyncio
async def test_valid_exact_official_pdb_is_qualified_with_safe_provenance(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A complete local PDB succeeds only after the existing exact validator runs."""
    pdb_text = exact_mev_pdb("AVLG")
    requested_urls: list[str] = []

    async def handler(request: httpx.Request) -> httpx.Response:
        requested_urls.append(str(request.url))
        return _pdb_response(pdb_text)

    transport = _core_transport(monkeypatch, handler)
    qualified = await transport.qualify_model_pdb(
        project_id="project-42",
        model_id="model-7",
        expected_sequence="AVLG",
    )

    assert requested_urls == [
        "https://swissmodel.expasy.org/project/project-42/model/model-7/pdb/"
    ]
    assert qualified.sequence_identity_validation["identityPercent"] == 100.0
    assert qualified.sequence_identity_validation["coveragePercent"] == 100.0
    assert qualified.transient_structure_input()["coordinateText"] == pdb_text
    public = qualified.public_provenance()
    assert public["modelUrl"] == requested_urls[0]
    assert "coordinateText" not in public
    assert_public_sinks_safe(public, transient_coordinate_text=pdb_text)


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "location",
    (
        "http://swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
        "https://127.0.0.1/private-model/",
        "https://user:pass@swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
    ),
)
async def test_redirects_to_non_https_private_or_credential_urls_are_rejected(
    monkeypatch: pytest.MonkeyPatch,
    location: str,
) -> None:
    """Unsafe redirect targets never receive a follow-up request."""
    requested_urls: list[str] = []

    async def handler(request: httpx.Request) -> httpx.Response:
        requested_urls.append(str(request.url))
        return httpx.Response(302, headers={"Location": location})

    transport = _core_transport(monkeypatch, handler)
    with pytest.raises(SwissModelPdbDownloadError) as rejected:
        await transport.qualify_model_pdb(
            project_id="project-42",
            model_id="model-7",
            expected_sequence="AVLG",
        )

    assert rejected.value.code == "pdb_redirect_invalid"
    assert requested_urls == [
        "https://swissmodel.expasy.org/project/project-42/model/model-7/pdb/"
    ]


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "unsafe_url",
    (
        "http://swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
        "https://127.0.0.1/project/project-42/model/model-7/pdb/",
        "https://user:pass@swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
    ),
)
async def test_malicious_provider_pdb_routes_are_rejected_before_network_access(
    monkeypatch: pytest.MonkeyPatch,
    unsafe_url: str,
) -> None:
    """The route itself must be official HTTPS before any model request is sent."""
    calls = 0

    async def handler(_request: httpx.Request) -> httpx.Response:
        nonlocal calls
        calls += 1
        return _pdb_response(exact_mev_pdb("AVLG"))

    transport = _core_transport(
        monkeypatch,
        handler,
        routes=_routes(model_pdb_url=lambda _project_id, _model_id: unsafe_url),
    )
    with pytest.raises(ValueError, match="official CoreAPI URL"):
        await transport.read_model_pdb(project_id="project-42", model_id="model-7")

    assert calls == 0


