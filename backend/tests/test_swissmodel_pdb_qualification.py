class _SucceededLifecycleTransport:
    """Local lifecycle fake that reports a completed provider project."""

    def __init__(self) -> None:
        self.create_calls: list[str] = []

    async def create_automodel(self, *, target_sequences: str) -> OfficialAutomodelReceipt:
        self.create_calls.append(target_sequences)
        return OfficialAutomodelReceipt(
            request_id="project-42",
            model_id="model-7",
            model_url="https://swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
            submitted_at=datetime(2025, 1, 2, tzinfo=timezone.utc),
        )

    async def read_project(self, *, project_id: str) -> OfficialSwissModelProject:
        assert project_id == "project-42"
        return OfficialSwissModelProject(state="succeeded")

    async def read_project_model_summary(
        self,
        *,
        project_id: str,
    ) -> OfficialSwissModelModelSummary:
        assert project_id == "project-42"
        return OfficialSwissModelModelSummary(
            model_id="model-7",
            model_url="https://swissmodel.expasy.org/project/project-42/model/model-7/pdb/",
        )


async def _no_sleep(_seconds: float) -> None:
    """Keep local retry-free lifecycle tests deterministic."""


@pytest.mark.asyncio
async def test_only_exact_qualified_coordinates_can_make_lifecycle_succeeded(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A terminal provider state becomes succeeded only with transient exact PDB data."""
    mev = completed_step_9_2_mev()
    pdb_text = exact_mev_pdb(mev.normalized_sequence)

    async def handler(_request: httpx.Request) -> httpx.Response:
        return _pdb_response(pdb_text)

    pdb_transport = _core_transport(monkeypatch, handler)
    preflight = preflight_swissmodel_submission(
        step_9_2_completed=True,
        step_9_2_sequence=mev.raw_sequence,
        current_mev_sequence=mev.normalized_sequence,
        current_mev_fingerprint=mev.fingerprint,
    )
    lifecycle_transport = _SucceededLifecycleTransport()
    lifecycle = SwissModelResilientLifecycle(
        lifecycle_transport,
        pdb_transport=pdb_transport,
        sleep=_no_sleep,
    )

    queued = await lifecycle.create_or_resume(preflight)
    succeeded: SwissModelLifecycleOutcome = await lifecycle.create_or_resume(preflight)

    assert queued.status.state == "queued"
    assert succeeded.status.state == "succeeded"
    assert succeeded.status.pdb_qualified is True
    assert succeeded.qualified_pdb is not None
    assert lifecycle_transport.create_calls == [mev.normalized_sequence]
    persisted = succeeded.persisted_record()
    assert persisted is not None
    assert "coordinateText" not in str(persisted)
    assert_public_sinks_safe(
        succeeded.public_result(),
        persisted,
        transient_coordinate_text=pdb_text,
    )


@pytest.mark.asyncio
async def test_rejected_official_pdb_pauses_without_structure_metrics(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A failed qualification creates neither a success state nor transient metric handoff."""
    mev = completed_step_9_2_mev()

    async def handler(_request: httpx.Request) -> httpx.Response:
        return _pdb_response(exact_mev_pdb("AVLA"))

    pdb_transport = _core_transport(monkeypatch, handler)
    preflight = preflight_swissmodel_submission(
        step_9_2_completed=True,
        step_9_2_sequence=mev.raw_sequence,
        current_mev_sequence=mev.normalized_sequence,
        current_mev_fingerprint=mev.fingerprint,
    )
    lifecycle = SwissModelResilientLifecycle(
        _SucceededLifecycleTransport(),
        pdb_transport=pdb_transport,
        sleep=_no_sleep,
    )

    await lifecycle.create_or_resume(preflight)
    paused = await lifecycle.create_or_resume(preflight)

    assert paused.status.state == "paused"
    assert paused.status.message_code == "swissmodel_pdb_qualification_failed"
    assert paused.status.pdb_qualified is False
    assert paused.qualified_pdb is None
    assert "pdbQualified" not in paused.public_result()
    assert_public_sinks_safe(paused.public_result(), paused.persisted_record())
